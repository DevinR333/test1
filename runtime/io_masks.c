/* Read masks for the IO registers.
 *
 * Most hardware registers have bits that do not exist. On real hardware those
 * read back as one, not zero. A game that tests an unused bit, or that masks a
 * register and compares against a constant, behaves differently when they read
 * as zero - and the usual symptom is a wait loop that never finishes.
 *
 * Each entry is OR-ed into the stored value on read.
 */
#include "gb.h"

const uint8_t gb_io_read_mask[128] = {
    [0x00] = 0xC0,                  /* JOYP: top two bits unused            */
    [0x01] = 0x00,                  /* SB                                    */
    [0x02] = 0x7C,                  /* SC: only clock and start exist on CGB */
    [0x03] = 0xFF,
    [0x04] = 0x00, [0x05] = 0x00, [0x06] = 0x00, [0x07] = 0xF8,  /* TAC */
    [0x08] = 0xFF, [0x09] = 0xFF, [0x0A] = 0xFF, [0x0B] = 0xFF,
    [0x0C] = 0xFF, [0x0D] = 0xFF, [0x0E] = 0xFF,
    [0x0F] = 0xE0,                  /* IF: five interrupts                   */

    /* Sound. The masks matter even without audio: a game reads these back. */
    [0x10] = 0x80, [0x11] = 0x3F, [0x12] = 0x00, [0x13] = 0xFF, [0x14] = 0xBF,
    [0x15] = 0xFF, [0x16] = 0x3F, [0x17] = 0x00, [0x18] = 0xFF, [0x19] = 0xBF,
    [0x1A] = 0x7F, [0x1B] = 0xFF, [0x1C] = 0x9F, [0x1D] = 0xFF, [0x1E] = 0xBF,
    [0x1F] = 0xFF, [0x20] = 0xFF, [0x21] = 0x00, [0x22] = 0x00, [0x23] = 0xBF,
    [0x24] = 0x00, [0x25] = 0x00, [0x26] = 0x70,
    [0x27] = 0xFF, [0x28] = 0xFF, [0x29] = 0xFF, [0x2A] = 0xFF, [0x2B] = 0xFF,
    [0x2C] = 0xFF, [0x2D] = 0xFF, [0x2E] = 0xFF, [0x2F] = 0xFF,
    /* 0x30-0x3F is wave RAM and reads back exactly. */

    [0x41] = 0x80,                  /* STAT: top bit unused                  */
    [0x4C] = 0xFF,
    [0x4D] = 0x7E,                  /* KEY1: speed and arming only           */
    [0x4E] = 0xFF,
    [0x4F] = 0xFE,                  /* VBK: one bit                          */
    [0x50] = 0xFF,
    [0x51] = 0xFF, [0x52] = 0xFF, [0x53] = 0xFF, [0x54] = 0xFF,  /* HDMA */
    [0x56] = 0x3E,                  /* RP: infrared, absent here             */
    [0x57] = 0xFF, [0x58] = 0xFF, [0x59] = 0xFF, [0x5A] = 0xFF, [0x5B] = 0xFF,
    [0x5C] = 0xFF, [0x5D] = 0xFF, [0x5E] = 0xFF, [0x5F] = 0xFF, [0x60] = 0xFF,
    [0x61] = 0xFF, [0x62] = 0xFF, [0x63] = 0xFF, [0x64] = 0xFF, [0x65] = 0xFF,
    [0x66] = 0xFF, [0x67] = 0xFF,
    [0x68] = 0x40, [0x6A] = 0x40,   /* palette index: bit 6 unused           */
    [0x6C] = 0xFE,                  /* OPRI                                  */
    [0x6D] = 0xFF, [0x6E] = 0xFF, [0x6F] = 0xFF,
    [0x70] = 0xF8,                  /* SVBK: three bits                      */
    [0x71] = 0xFF,
    [0x75] = 0x8F,                  /* undocumented, three writable bits     */
    [0x78] = 0xFF, [0x79] = 0xFF, [0x7A] = 0xFF, [0x7B] = 0xFF,
    [0x7C] = 0xFF, [0x7D] = 0xFF, [0x7E] = 0xFF,
};
