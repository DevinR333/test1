int gb_text_width(const char *text, int scale)
{
    return (int)strlen(text) * 6 * scale;
}

void gb_text_draw(uint32_t *dst, int dst_w, int dst_h, int x, int y,
                  const char *text, uint32_t colour, int scale)
{
    if (!dst || !text || scale < 1) return;

    for (const char *p = text; *p; p++) {
        int c = (unsigned char)*p;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 32 || c >= 96) c = 32;
        const uint8_t *g = FONT[c - 32];

        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (!((g[row] >> (4 - col)) & 1)) continue;
                for (int sy = 0; sy < scale; sy++) {
                    int py = y + row * scale + sy;
                    if (py < 0 || py >= dst_h) continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int px = x + col * scale + sx;
                        if (px < 0 || px >= dst_w) continue;
                        dst[(size_t)py * dst_w + px] = colour;
                    }
                }
            }
        }
        x += 6 * scale;
    }
}

/* Drawn into the picture rather than by the platform, so it looks the same on
 * a desktop and on a handheld and needs nothing but somewhere to put pixels. */
void gb_menu_draw(uint32_t *dst, int dst_w, int dst_h, int selected)
{
    if (!dst || dst_w < 80 || dst_h < 60) return;

    static const char *HINT = "UP DOWN TO CHOOSE - START OR A TO PLAY";

    int scale = dst_h / 260;
    if (scale < 1) scale = 1;
    if (scale > 5) scale = 5;

    int line = 11 * scale;
    int pad = 9 * scale;
    int rows = GB_VIEW_MODES;

    /* Wide enough for the longest line it will actually draw, the hint
     * included - sized to the options alone, the hint ran off the edge. */
    int w = gb_text_width(HINT, scale);
    for (int i = 0; i < rows; i++) {
        int t = gb_text_width(gb_view_note(i), scale);
        if (t > w) w = t;
        t = gb_text_width(gb_view_name(i), scale);
        if (t > w) w = t;
    }
    w += pad * 4;                     /* margin, and room for the marker */
    int h = pad * 2 + line * (rows * 2 + 3);
    if (w > dst_w - 8) w = dst_w - 8;
    if (h > dst_h - 8) h = dst_h - 8;

    int x0 = (dst_w - w) / 2, y0 = (dst_h - h) / 2;

    /* A panel dark enough to read against anything behind it. */
    for (int y = y0; y < y0 + h; y++) {
        if (y < 0 || y >= dst_h) continue;
        for (int x = x0; x < x0 + w; x++) {
            if (x < 0 || x >= dst_w) continue;
            int edge = (y < y0 + scale || y >= y0 + h - scale
                        || x < x0 + scale || x >= x0 + w - scale);
            uint32_t *p = &dst[(size_t)y * dst_w + x];
            *p = edge ? 0xFFE0C080u : (((*p >> 2) & 0x3F3F3F) | 0xFF101018u);
        }
    }

    int y = y0 + pad;
    gb_text_draw(dst, dst_w, dst_h, x0 + pad * 2, y, "DISPLAY MODE", 0xFFE0C080u, scale);
    y += line * 2;

    for (int i = 0; i < rows; i++) {
        uint32_t c = (i == selected) ? 0xFFFFFFFFu : 0xFF9098A8u;
        if (i == selected)
            gb_text_draw(dst, dst_w, dst_h, x0 + pad * 2 - 6 * scale, y, ">",
                         0xFFE0C080u, scale);
        gb_text_draw(dst, dst_w, dst_h, x0 + pad * 2, y, gb_view_name(i), c, scale);
        gb_text_draw(dst, dst_w, dst_h, x0 + pad * 2, y + line,
                     gb_view_note(i), (i == selected) ? 0xFFB0B8C8u : 0xFF606878u,
                     scale);
        y += line * 2;
    }

    gb_text_draw(dst, dst_w, dst_h, x0 + pad * 2, y + line / 2,
                 HINT, 0xFF808898u, scale);
}
