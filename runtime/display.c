/* Framing, and the chooser for it. See display.h. */
#include <string.h>
#include "display.h"

#define GB_W 160
#define GB_H 144

const char *gb_view_name(gb_view_mode_t mode)
{
    switch (mode) {
    case GB_VIEW_16_9: return "WIDESCREEN 16:9";
    case GB_VIEW_4_3:  return "STANDARD 4:3";
    default:           return "OPEN WORLD";
    }
}

const char *gb_view_note(gb_view_mode_t mode)
{
    switch (mode) {
    case GB_VIEW_16_9: return "THE GAME SCREEN IN A 16:9 FRAME";
    case GB_VIEW_4_3:  return "THE GAME SCREEN IN A 4:3 FRAME";
    default:           return "THE WORLD DRAWN AROUND THE GAME";
    }
}

/* The largest rectangle of the mode's shape that fits the window. The open
 * world has no shape of its own - it is drawn to whatever the window is,
 * which is the whole point of it. */
gb_rect_t gb_view_frame(gb_view_mode_t mode, int win_w, int win_h)
{
    gb_rect_t r = { 0, 0, win_w, win_h };
    int aw = 0, ah = 0;

    if (mode == GB_VIEW_16_9) { aw = 16; ah = 9; }
    else if (mode == GB_VIEW_4_3) { aw = 4; ah = 3; }
    else return r;

    if (win_w * ah > win_h * aw) {          /* window wider than the frame */
        r.h = win_h;
        r.w = win_h * aw / ah;
    } else {
        r.w = win_w;
        r.h = win_w * ah / aw;
    }
    r.x = (win_w - r.w) / 2;
    r.y = (win_h - r.h) / 2;
    return r;
}

/* Inside that frame, the hardware's screen at its own shape. Whole multiples
 * where one fits, so the pixels stay square and none is doubled while its
 * neighbour is not. */
gb_rect_t gb_view_screen(gb_view_mode_t mode, int win_w, int win_h)
{
    gb_rect_t f = gb_view_frame(mode, win_w, win_h);
    gb_rect_t r;

    int scale = f.w / GB_W;
    int by = f.h / GB_H;
    if (by < scale) scale = by;
    if (scale < 1) scale = 1;

    r.w = GB_W * scale;
    r.h = GB_H * scale;
    r.x = f.x + (f.w - r.w) / 2;
    r.y = f.y + (f.h - r.h) / 2;
    return r;
}

