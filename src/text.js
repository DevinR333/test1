    'N': '#...#|##..#|#.#.#|#..##|#...#|#...#|.....',
    'O': '.###.|#...#|#...#|#...#|#...#|.###.|.....',
    'P': '####.|#...#|####.|#....|#....|#....|.....',
    'Q': '.###.|#...#|#...#|#.#.#|#..#.|.##.#|.....',
    'R': '####.|#...#|####.|#.#..|#..#.|#...#|.....',
    'S': '.####|#....|.###.|....#|....#|####.|.....',
    'T': '#####|..#..|..#..|..#..|..#..|..#..|.....',
    'U': '#...#|#...#|#...#|#...#|#...#|.###.|.....',
    'V': '#...#|#...#|#...#|#...#|.#.#.|..#..|.....',
    'W': '#...#|#...#|#...#|#.#.#|##.##|#...#|.....',
    'X': '#...#|.#.#.|..#..|..#..|.#.#.|#...#|.....',
